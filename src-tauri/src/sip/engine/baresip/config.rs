//! Generation of Baresip's `config` file and `uanew` account lines.
//!
//! Security notes:
//! * The control interface is always bound to `127.0.0.1` on a random port;
//!   Baresip's default would be `0.0.0.0:4444`.
//! * No `accounts` file is ever written: accounts (with their password) are
//!   created over the loopback control socket and exist only in memory.
//! * `sip_verify_server` is never disabled.

use std::path::{Path, PathBuf};

use secrecy::ExposeSecret;

use crate::sip::engine::AccountSpec;
use crate::sip::types::{MediaEncryption, Transport};
use crate::sip::uri::host_for_uri;

/// Audio driver module for the current platform.
pub fn audio_driver() -> &'static str {
    if cfg!(target_os = "macos") {
        "coreaudio"
    } else if cfg!(target_os = "windows") {
        "winwave"
    } else {
        "alsa"
    }
}

pub fn module_ext() -> &'static str {
    if cfg!(windows) { "dll" } else { "so" }
}

pub use crate::sip::engine::EngineOptions as EngineSettings;

/// Device names are placed on a single config line: refuse anything that could
/// break out of it and fall back to the system default.
pub fn sanitize_device(name: Option<&str>) -> String {
    match name.map(str::trim) {
        Some(n) if !n.is_empty() && n.len() < 120 && !n.chars().any(|c| c.is_control() || c == '#') => n.to_owned(),
        _ => "default".to_owned(),
    }
}

/// Default CA bundle for the platform, if one exists on disk.
pub fn system_ca_file() -> Option<PathBuf> {
    [
        "/etc/ssl/cert.pem",                   // macOS, *BSD
        "/etc/ssl/certs/ca-certificates.crt",  // Debian/Ubuntu
        "/etc/pki/tls/certs/ca-bundle.crt",    // Fedora/RHEL
        "/etc/ssl/ca-bundle.pem",              // openSUSE
    ]
    .iter()
    .map(PathBuf::from)
    .find(|p| p.is_file())
}

pub struct ConfigInput<'a> {
    pub modules_dir: &'a Path,
    pub sounds_dir: &'a Path,
    pub ctrl_port: u16,
    pub settings: &'a EngineSettings,
    /// Tells whether a module file exists (optional codecs are loaded only if shipped).
    pub module_exists: &'a dyn Fn(&str) -> bool,
}

fn path_value(p: &Path) -> String {
    // Config values are single lines.
    p.to_string_lossy().replace(['\n', '\r'], "")
}

/// Optional modules loaded when present in the module directory.
pub const OPTIONAL_CODEC_MODULES: &[&str] = &["g722", "opus"];

pub fn render_config(input: &ConfigInput<'_>) -> String {
    let ext = module_ext();
    let driver = audio_driver();
    let player = sanitize_device(input.settings.output_device.as_deref());
    let source = sanitize_device(input.settings.input_device.as_deref());
    let ca = input.settings.ca_file.clone().or_else(system_ca_file);

    let mut c = String::new();
    c.push_str("# Generated by ZePhone at every engine start. Do not edit.\n");
    c.push_str("call_local_timeout\t120\n");
    c.push_str("call_max_calls\t\t4\n");
    c.push_str("call_hold_other_calls\tyes\n");
    c.push_str(&format!("audio_player\t\t{driver},{player}\n"));
    c.push_str(&format!("audio_source\t\t{driver},{source}\n"));
    c.push_str(&format!("audio_alert\t\t{driver},{player}\n"));
    c.push_str(&format!("audio_path\t\t{}\n", path_value(input.sounds_dir)));
    c.push_str("ring_aufile\t\tring.wav\n");
    c.push_str("ringback_aufile\t\tringback.wav\n");
    c.push_str("audio_telev_pt\t\t101\n");
    c.push_str("audio_jitter_buffer_type\tadaptive\n");
    c.push_str("audio_jitter_buffer_ms\t20-300\n");
    c.push_str("sip_verify_server\tyes\n");
    if let Some(ca) = ca {
        c.push_str(&format!("sip_cafile\t\t{}\n", path_value(&ca)));
    }
    c.push_str(&format!("module_path\t\t{}\n", path_value(input.modules_dir)));
    c.push_str(&format!("module\t\t\tg711.{ext}\n"));
    for m in OPTIONAL_CODEC_MODULES {
        if (input.module_exists)(&format!("{m}.{ext}")) {
            c.push_str(&format!("module\t\t\t{m}.{ext}\n"));
        }
    }
    c.push_str(&format!("module\t\t\tauconv.{ext}\n"));
    c.push_str(&format!("module\t\t\tauresamp.{ext}\n"));
    c.push_str(&format!("module\t\t\t{driver}.{ext}\n"));
    c.push_str(&format!("module\t\t\tsrtp.{ext}\n"));
    c.push_str(&format!("module_app\t\tmenu.{ext}\n"));
    c.push_str(&format!("module_app\t\tctrl_tcp.{ext}\n"));
    c.push_str(&format!("ctrl_tcp_listen\t\t127.0.0.1:{}\n", input.ctrl_port));
    c
}

/// Builds the argument of the `uanew` command.
///
/// Values containing `;`, spaces or `>` are safe because they are quoted;
/// callers must have validated that none of them contains `"` (see
/// [`crate::sip::uri`]). The returned string contains the password: never log
/// it without [`crate::security::redact::redact`].
pub fn account_line(spec: &AccountSpec) -> String {
    let transport = match spec.transport {
        Transport::Udp => String::new(),
        t => format!(";transport={}", t.as_param()),
    };

    let mut line = String::new();
    if let Some(name) = spec.display_name.as_deref().filter(|n| !n.is_empty()) {
        line.push_str(&format!("\"{name}\" "));
    }
    line.push_str(&format!("<sip:{}@{}{}>", spec.username, host_for_uri(&spec.domain), transport));

    let auth_user = spec.auth_username.as_deref().unwrap_or(&spec.username);
    line.push_str(&format!(";auth_user=\"{auth_user}\""));
    line.push_str(&format!(";auth_pass=\"{}\"", spec.password.expose_secret()));
    line.push_str(&format!(
        ";outbound1=\"sip:{}:{};transport={}\"",
        host_for_uri(&spec.next_hop_host),
        spec.next_hop_port,
        spec.transport.as_param()
    ));
    line.push_str(&format!(";regint={}", spec.register_interval));
    match spec.media_encryption {
        MediaEncryption::None => {}
        MediaEncryption::Srtp => line.push_str(";mediaenc=srtp"),
        MediaEncryption::SrtpMandatory => line.push_str(";mediaenc=srtp-mand"),
    }
    line
}

#[cfg(test)]
mod tests {
    use super::*;
    use secrecy::SecretString;

    fn spec() -> AccountSpec {
        AccountSpec {
            aor: "sip:1001@example.com".into(),
            username: "1001".into(),
            domain: "example.com".into(),
            auth_username: None,
            password: SecretString::from("s3cr;et w>ord".to_string()),
            display_name: Some("Ada Lovelace".into()),
            transport: Transport::Tls,
            next_hop_host: "sip.example.com".into(),
            next_hop_port: 5061,
            register_interval: 300,
            media_encryption: MediaEncryption::Srtp,
        }
    }

    #[test]
    fn account_line_shape() {
        let line = account_line(&spec());
        assert_eq!(
            line,
            "\"Ada Lovelace\" <sip:1001@example.com;transport=tls>;auth_user=\"1001\";auth_pass=\"s3cr;et w>ord\";\
             outbound1=\"sip:sip.example.com:5061;transport=tls\";regint=300;mediaenc=srtp"
        );
    }

    #[test]
    fn udp_account_has_no_transport_in_aor_and_uses_auth_user() {
        let mut s = spec();
        s.transport = Transport::Udp;
        s.display_name = None;
        s.media_encryption = MediaEncryption::None;
        s.auth_username = Some("auth1001".into());
        let line = account_line(&s);
        assert!(line.starts_with("<sip:1001@example.com>;auth_user=\"auth1001\""));
        assert!(!line.contains("mediaenc"));
        assert!(line.contains("outbound1=\"sip:sip.example.com:5061;transport=udp\""));
    }

    #[test]
    fn ipv6_hosts_are_bracketed() {
        let mut s = spec();
        s.next_hop_host = "2001:db8::10".into();
        s.domain = "2001:db8::10".into();
        let line = account_line(&s);
        assert!(line.contains("<sip:1001@[2001:db8::10];transport=tls>"));
        assert!(line.contains("outbound1=\"sip:[2001:db8::10]:5061;"));
    }

    #[test]
    fn config_binds_control_to_loopback_only() {
        let settings = EngineSettings::default();
        let exists = |m: &str| m == "opus.so";
        let cfg = render_config(&ConfigInput {
            modules_dir: Path::new("/app/modules"),
            sounds_dir: Path::new("/app/sounds"),
            ctrl_port: 45678,
            settings: &settings,
            module_exists: &exists,
        });
        assert!(cfg.contains("ctrl_tcp_listen\t\t127.0.0.1:45678\n"));
        assert!(!cfg.contains("0.0.0.0"));
        assert!(cfg.contains("sip_verify_server\tyes"));
        assert!(!cfg.contains("sip_verify_server\tno"));
        assert!(cfg.contains("module_path\t\t/app/modules"));
        assert!(cfg.contains("g711.so"));
        assert!(cfg.contains("opus.so"));
        assert!(!cfg.contains("g722.so"));
        // No console / http / accounts modules.
        for forbidden in ["cons.so", "httpd.so", "stdio.so", "account.so"] {
            assert!(!cfg.contains(forbidden), "{forbidden} must not be loaded");
        }
    }

    #[test]
    fn device_names_are_sanitised() {
        assert_eq!(sanitize_device(None), "default");
        assert_eq!(sanitize_device(Some("")), "default");
        assert_eq!(sanitize_device(Some("MacBook Pro Microphone")), "MacBook Pro Microphone");
        assert_eq!(sanitize_device(Some("evil\nmodule foo.so")), "default");
        assert_eq!(sanitize_device(Some("x # y")), "default");
    }

    #[test]
    fn selected_devices_end_up_in_config() {
        let settings = EngineSettings {
            input_device: Some("USB Mic".into()),
            output_device: Some("AirPods".into()),
            ..Default::default()
        };
        let cfg = render_config(&ConfigInput {
            modules_dir: Path::new("/m"),
            sounds_dir: Path::new("/s"),
            ctrl_port: 1,
            settings: &settings,
            module_exists: &|_| false,
        });
        let d = audio_driver();
        assert!(cfg.contains(&format!("audio_source\t\t{d},USB Mic\n")));
        assert!(cfg.contains(&format!("audio_player\t\t{d},AirPods\n")));
        assert!(cfg.contains(&format!("audio_alert\t\t{d},AirPods\n")));
    }
}
