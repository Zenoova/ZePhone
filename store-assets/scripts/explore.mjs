import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const p = await b.newPage();
await p.setViewport({ width: 440, height: 760, deviceScaleFactor: 2 });
await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "light" }]);
await p.goto("http://localhost:1420/?mock=showcase&window=call", { waitUntil: "networkidle0" });
const id = await p.evaluate(() => window.__mock.incoming("Alice Durand", "1001"));
await sleep(600);
await p.evaluate((i) => window.__TAURI_INTERNALS__.invoke("answer_call", { id: i }), id);
await sleep(8000);
await p.click('button[aria-label="Call options"]');
await sleep(700);
await p.click("::-p-text(Advanced statistics)");
await sleep(3500);
await p.screenshot({ path: "captures/explore-stats.png" });
await b.close();
